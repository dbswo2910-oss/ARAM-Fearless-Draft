'use strict';
const fs=require('fs'),path=require('path');
const ROOT=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(ROOT,p),'utf8');
const exists=p=>fs.existsSync(path.join(ROOT,p));
const report={generatedAt:new Date().toISOString(),pass:[],fail:[],info:{}};
const ok=(cond,name,detail='')=>(cond?report.pass:report.fail).push({name,detail});
const m=JSON.parse(read('update/manifest.json'));
const byPath=new Map((m.files||[]).map(x=>[x.path,x.source]));
const patchPath=byPath.get('draft-layout-hotfix-v01544.js');
const mainPath=byPath.get('main.js');
ok(m.version==='0.15.44','Manifest is v0.15.44',m.version);
ok(!!patchPath&&exists(patchPath),'v0.15.44 hotfix runtime delivered',patchPath||'missing');
const s=patchPath&&exists(patchPath)?read(patchPath):'';
const main=mainPath&&exists(mainPath)?read(mainPath):'';
ok(/__ARAM_DRAFT_LAYOUT_HOTFIX_V01544__\s*=\s*true/.test(s),'v0.15.44 readiness marker');
ok(/\^\\s\*\\d\+픽\\s\*추천/.test(s)&&/실시간.*픽.*추천/.test(s),'Dynamic N-pick recommendation title is detected');
ok(/이번\\s\*세트.*밴/.test(s)&&/위협\\s\*밴/.test(s),'Current-set threat-ban panel is detected');
ok(/grid-template-columns:minmax\(0,50%\) minmax\(0,50%\)/.test(s),'Top draft rows use equal left/right columns');
ok(/draftV01543LeftOnly/.test(s)&&/width:calc\(50% - 5px\)/.test(s),'BAN/PICK left panels share the same width');
ok(/builderWorkspaceV01544Compact/.test(s)&&/min-height:0!important/.test(s),'Old workspace no longer preserves the large blank vertical gap');
ok(/실시간 다음 픽 추천 TOP 6/.test(s)&&/우리 4~5밴 추천 TOP 6/.test(s),'Recommendation headings are normalized');
ok(/score_logic_changed:false/.test(s),'Hotfix is layout-only and does not change scoring');
ok(main.includes("'draft-balance-alerts-v01543.js','draft-layout-hotfix-v01544.js','role-metric-detail-v01518.js'"),'Main injects v0.15.44 after v0.15.43');
