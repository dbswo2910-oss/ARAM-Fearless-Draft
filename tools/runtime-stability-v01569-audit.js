'use strict';
const fs=require('fs'),path=require('path');
const ROOT=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(ROOT,p),'utf8');
const exists=p=>fs.existsSync(path.join(ROOT,p));
const report={version:'0.15.69',generated_at:new Date().toISOString(),checks:[]};
const ok=(name,pass,detail='')=>report.checks.push({name,pass:!!pass,detail});
const m=JSON.parse(read('update/manifest.json'));
const byPath=new Map((m.files||[]).map(x=>[x.path,x.source]));
const mainPath=byPath.get('main.js'),pkgPath=byPath.get('package.json'),perfPath=byPath.get('runtime-performance-v01568.js');
const main=mainPath&&exists(mainPath)?read(mainPath):'',pkg=pkgPath&&exists(pkgPath)?JSON.parse(read(pkgPath)):{};
try{new Function(main);ok('main parses',true)}catch(e){ok('main parses',false,e.message)}
ok('manifest version 0.15.69',m.version==='0.15.69',m.version);
ok('package version 0.15.69',pkg.version==='0.15.69',pkg.version);
ok('manifest maps v0.15.69 main',mainPath==='update/v0.15.69/main.js',mainPath||'missing');
ok('manifest maps v0.15.69 package',pkgPath==='update/v0.15.69/package.json',pkgPath||'missing');
ok('v0.15.68 performance runtime remains active',perfPath==='update/v0.15.68/runtime-performance-v01568.js',perfPath||'missing');
const startupOld="setTimeout(()=>runEngineRegressionTests(false),30)";
const startupNew="setTimeout(()=>{if(!window.aramDesktop?.isElectron)runEngineRegressionTests(false)},30)";
const dataOld="function ensureRegressionRun(){if(!regressionLastRun)runEngineRegressionTests(true);else renderRegressionResults()}";
const dataNew="function ensureRegressionRun(){renderRegressionResults()}";
ok('known startup Golden Guard marker is targeted exactly',main.includes(`const startupOld=${JSON.stringify(startupOld)}`));
ok('Electron startup skips automatic Golden Guard',main.includes(`const startupNew=${JSON.stringify(startupNew)}`));
ok('known Data-tab autorun marker is targeted exactly',main.includes(`const dataOld=${JSON.stringify(dataOld)}`));
ok('Data tab becomes display-only until manual test run',main.includes(`const dataNew=${JSON.stringify(dataNew)}`));
ok('base UI patch runs before loadFile',main.indexOf('prepareBaseUiForRuntime();')>=0&&main.indexOf('prepareBaseUiForRuntime();')<main.indexOf('mainWindow.loadFile('));
ok('original index backup is preserved once',main.includes("index.pre-v01569-auto-regression.bak.html")&&main.includes("if(!fs.existsSync(backup))fs.copyFileSync(p,backup)"));
ok('manual regression function itself is not replaced globally',!main.includes('window.runEngineRegressionTests=')&&!main.includes('runEngineRegressionTests=()=>'));
ok('no score/recommendation implementation is edited by v0.15.69 main',!main.includes('function recommendPicks(')&&!main.includes('function recommendBans(')&&!main.includes('function teamScore('));
let fixture=`<button onclick="runEngineRegressionTests(true)">전체 테스트 다시 실행</button>\n${dataOld}\nfunction init(){${startupOld}}`;
let patched=fixture.replace(startupOld,startupNew).replace(dataOld,dataNew);
ok('fixture removes startup autorun in Electron',!patched.includes(startupOld)&&patched.includes(startupNew));
ok('fixture removes Data-tab autorun',!patched.includes(dataOld)&&patched.includes(dataNew));
ok('fixture preserves manual regression button',patched.includes('onclick="runEngineRegressionTests(true)"'));
report.pass=report.checks.every(x=>x.pass);
fs.mkdirSync(path.join(ROOT,'audit-output'),{recursive:true});
fs.writeFileSync(path.join(ROOT,'audit-output/runtime-stability-v01569-report.json'),JSON.stringify(report,null,2));
for(const c of report.checks)console.log(`${c.pass?'PASS':'FAIL'} ${c.name}${c.detail?' · '+c.detail:''}`);
if(!report.pass)process.exit(1);
