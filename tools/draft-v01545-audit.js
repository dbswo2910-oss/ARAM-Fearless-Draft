'use strict';
const fs=require('fs'),path=require('path');
const ROOT=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(ROOT,p),'utf8');
const exists=p=>fs.existsSync(path.join(ROOT,p));
const report={generatedAt:new Date().toISOString(),pass:[],fail:[],info:{}};
const ok=(cond,name,detail='')=>(cond?report.pass:report.fail).push({name,detail});
const m=JSON.parse(read('update/manifest.json'));
const byPath=new Map((m.files||[]).map(x=>[x.path,x.source]));
const layoutPath=byPath.get('draft-layout-v01545.js');
const balancePath=byPath.get('draft-balance-alerts-v01543.js');
const mainPath=byPath.get('main.js');
ok(m.version==='0.15.45','Manifest is v0.15.45',m.version);
ok(!!layoutPath&&exists(layoutPath),'v0.15.45 stable layout runtime delivered',layoutPath||'missing');
ok(!!balancePath&&/v0\.15\.45\/draft-balance-alerts-v01543-clean\.js$/.test(balancePath),'v0.15.43 runtime is remapped to cleaned no-layout source',balancePath||'missing');
ok((m.delete||[]).includes('draft-layout-hotfix-v01544.js'),'Broken v0.15.44 installed runtime is deleted');
ok(!byPath.has('draft-layout-hotfix-v01544.js'),'Broken v0.15.44 runtime is not delivered');
const s=layoutPath&&exists(layoutPath)?read(layoutPath):'';
const balance=balancePath&&exists(balancePath)?read(balancePath):'';
const main=mainPath&&exists(mainPath)?read(mainPath):'';
ok(/__ARAM_DRAFT_LAYOUT_V01545__\s*=\s*true/.test(s),'v0.15.45 readiness marker');
ok(/draftPhase1SectionV01545/.test(s)&&/draftPhase2SectionV01545/.test(s),'BAN 1-3 and BAN 4-5 use equal-width left sections');
ok(/moveAfter\(p1,p2\)/.test(s)&&/moveAfter\(p2,current\)/.test(s),'Left stack orders BAN1-3 -> BAN4-5 -> current picks with no grid-row height coupling');
ok(/moveAfter\(current,engine\)/.test(s)&&/moveAfter\(engine\|\|current,pool\)/.test(s),'Pick judgment and champion pool follow current picks in the left stack');
ok(/moveAfter\(pr,br\)/.test(s)&&/draftRightStackV01545/.test(s),'Right stack orders next-pick TOP6 -> our-ban TOP6 independently');
ok(/root\.querySelector\('\.currentPickGrid'\)/.test(s)&&!/closest\('\.panel/.test(s),'Current-pick relocation targets the leaf grid, not an oversized parent panel');
ok(/width:100%!important;max-width:100%!important/.test(s),'Left sections are normalized to the same host width');
ok(/independent_column_flow:true/.test(s)&&/score_logic_changed:false/.test(s),'Layout uses independent column flow and does not change scoring');
ok(!/grid-template-columns/.test(s),'No artificial 50/50 row grid remains in v0.15.45 layout');
ok(/layout_manipulation:false/.test(balance),'Balance/alert runtime does not move layout');
ok(main.includes("'draft-live-context-v01542.js','draft-balance-alerts-v01543.js','draft-layout-v01545.js','role-metric-detail-v01518.js'"),'Main injection order is live context -> clean balance/alerts -> stable layout');
ok(!main.includes("'draft-layout-hotfix-v01544.js'"),'Main no longer injects v0.15.44 hotfix');
ok(main.includes('__ARAM_DRAFT_LAYOUT_V01545__')&&!main.includes('__ARAM_DRAFT_LAYOUT_HOTFIX_V01544__'),'Main readiness guard uses v0.15.45 layout marker only');
ok(/const VERSION='0\.15\.45'/.test(main),'Main VERSION is v0.15.45');
report.summary={pass:report.pass.length,fail:report.fail.length,status:report.fail.length?'FAIL':'PASS'};
fs.mkdirSync(path.join(ROOT,'audit-output'),{recursive:true});
fs.writeFileSync(path.join(ROOT,'audit-output','draft-v01545-report.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify(report.summary));
for(const x of report.fail)console.error('FAIL',x.name,x.detail||'');
process.exitCode=report.fail.length?1:0;
