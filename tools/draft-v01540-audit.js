'use strict';
const fs=require('fs'),path=require('path');
const ROOT=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(ROOT,p),'utf8');
const exists=p=>fs.existsSync(path.join(ROOT,p));
const report={generatedAt:new Date().toISOString(),pass:[],fail:[],info:{}};
const ok=(cond,name,detail='')=>(cond?report.pass:report.fail).push({name,detail});
const m=JSON.parse(read('update/manifest.json'));
const byPath=new Map((m.files||[]).map(x=>[x.path,x.source]));
const catchPath=byPath.get('catch-resilience-v01540.js');
const sidePath=byPath.get('draft-side-order-v01540.js');
const mainPath=byPath.get('main.js');
ok(m.version==='0.15.40','Manifest is v0.15.40',m.version);
ok(!!catchPath&&exists(catchPath),'Catch resilience runtime delivered',catchPath||'missing');
ok(!!sidePath&&exists(sidePath),'Draft side-order runtime delivered',sidePath||'missing');
const c=catchPath&&exists(catchPath)?read(catchPath):'';
const s=sidePath&&exists(sidePath)?read(sidePath):'';
const main=mainPath&&exists(mainPath)?read(mainPath):'';
ok(/__ARAM_CATCH_RESILIENCE_V01540__\s*=\s*true/.test(c),'Catch readiness marker');
ok(/__ARAM_DRAFT_SIDE_ORDER_V01540__\s*=\s*true/.test(s),'Side-order readiness marker');
ok(/directLayer\s*=\s*r\.direct\*1\.35/.test(c)&&/allyLayer\s*=\s*r\.allyEffective\*\.72/.test(c),'Direct self-save weighted above ally save');
ok(/clamp\(raw\*pressure\.scale\*reveal,0,7\.5\)/.test(c),'Catch response bonus is capped at 7.5');
ok(/catch_activation:7/.test(c),'Catch response activates only beyond baseline 7');
ok(/role_grade_impact:false/.test(c)&&/riot_grade_impact:false/.test(c),'ROLE/Riot Grade scoring isolation');
ok(/NEW · 상대 캐치 생존 대응/.test(c)&&/NEW · 우리 캐치 무력화 위험/.test(c),'Score detail exposes catch-survival delta');
ok(/<span>생존<\/span>/.test(c)&&/캐치대응 · 직접생존 우선/.test(c),'Completed comp metrics expose survival card');
ok(/sequence_changed:false/.test(s),'Draft sequence explicitly unchanged');
ok(/currentPickGrid/.test(s)&&/liveBanGrid/.test(s)&&/liveDraftGrid/.test(s),'Local builder/live draft are side-ordered');
ok(/onlineDraftGrid/.test(s)&&/onlineScoreboard/.test(s),'Online mock draft is side-ordered');
ok(/blue=onlineState\.firstTeam==='B'\?'B':'A'/.test(s),'Online BLUE team is derived from firstTeam');
ok(main.includes("'catch-resilience-v01540.js'")&&main.includes("'draft-side-order-v01540.js'"),'Main injects both v0.15.40 runtimes');
ok(main.includes('__ARAM_CATCH_RESILIENCE_V01540__')&&main.includes('__ARAM_DRAFT_SIDE_ORDER_V01540__'),'Main readiness guard covers both v0.15.40 runtimes');
report.summary={pass:report.pass.length,fail:report.fail.length,status:report.fail.length?'FAIL':'PASS'};
fs.mkdirSync(path.join(ROOT,'audit-output'),{recursive:true});
fs.writeFileSync(path.join(ROOT,'audit-output','draft-v01540-report.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify(report.summary));
for(const x of report.fail)console.error('FAIL',x.name,x.detail||'');
process.exitCode=report.fail.length?1:0;
