'use strict';
const assert=require('assert');
const fs=require('fs');
const path=require('path');
const ROOT=process.cwd();
const plan=require(path.join(ROOT,'src/rc/activation-plan.js'));
const manifest=JSON.parse(fs.readFileSync(path.join(ROOT,'update/manifest.json'),'utf8'));
const d=plan.activationDescriptor();
assert.strictEqual(d.version,'0.16.0-rc.1');
assert.strictEqual(d.golden,'0.15.135');
assert.strictEqual(manifest.version,'0.15.135','isolated RC must not mutate production manifest');
assert.strictEqual(d.production_manifest_mutation,false);
assert.strictEqual(d.legacy_removal,false);
assert.strictEqual(d.user_data_id,'aram-fearless-draft');
assert.strictEqual(d.research_db,'aram-rating-research-v03');
assert.strictEqual(d.research_checkpoint,'checkpoint-v03');
assert.ok(d.owners.length>=15);
const out=path.join(ROOT,'audit-output','stability','rc-activation-report.json');
fs.mkdirSync(path.dirname(out),{recursive:true});
fs.writeFileSync(out,JSON.stringify({status:'SUCCESS',stage:'V0160_ISOLATED_RC_ACTIVATION_PREFLIGHT',...d},null,2));
console.log('V0.16 ISOLATED RC ACTIVATION PREFLIGHT: SUCCESS',JSON.stringify({version:d.version,owners:d.owners.length,golden:d.golden}));
